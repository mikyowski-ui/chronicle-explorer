import { defineConfig, type Plugin } from 'vite';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';

const appRoot = fileURLToPath(new URL('./', import.meta.url));
const repoRoot = fileURLToPath(new URL('../..', import.meta.url));
const sha256 = (value: string | Uint8Array) => createHash('sha256').update(value).digest('hex');

async function filesBelow(root: string): Promise<string[]> {
  const files: string[] = [];
  for (const item of await readdir(root, { withFileTypes: true })) {
    const path = join(root, item.name);
    if (['node_modules', '.sites-runtime', '__pycache__'].includes(item.name)) continue;
    if (item.isSymbolicLink()) throw new Error('Build identity does not follow source symlinks: ' + path);
    if (item.isDirectory()) files.push(...await filesBelow(path));
    else if (item.isFile()) files.push(path);
  }
  return files.sort();
}

/** Static identity is generated by the existing Vite build, not a second packager. */
function chronicleBuildIdentity(): Plugin {
  return {
    name: 'chronicle-build-identity',
    apply: 'build',
    async generateBundle() {this.emitFile({type:'asset',fileName:'production-review.html',source:await readFile(join(appRoot,'production-review.html'),'utf8')});},
    async writeBundle(options, bundle) {
      const paths = [
        ...await filesBelow(join(appRoot, 'src')),
        ...await filesBelow(join(appRoot, 'research-semantic')),
        ...await filesBelow(join(appRoot, 'runtime-isolation')),
        ...await filesBelow(join(appRoot, 'verification-tools')),
        ...await filesBelow(join(repoRoot, 'packages/contracts/src')),
        ...await filesBelow(join(appRoot, 'public')),
        ...['index.html', 'production-review.html', 'vite.config.ts', 'package.json', 'pnpm-lock.yaml'].map(name => join(appRoot, name)),
      ].sort();
      const sourceInputs = [];
      for (const path of paths) {
        const bytes = await readFile(path);
        sourceInputs.push({ path: relative(repoRoot, path).replaceAll('\\', '/'), byte_length: bytes.length, sha256: sha256(bytes) });
      }
      const bundleFiles = Object.entries(bundle).sort(([a], [b]) => a.localeCompare(b)).map(([path, entry]) => {
        const content = entry.type === 'chunk' ? entry.code : entry.source;
        const bytes = typeof content === 'string' ? Buffer.from(content) : content;
        return { path, byte_length: bytes.length, sha256: sha256(bytes) };
      });
      const sourceFingerprint = sha256(JSON.stringify(sourceInputs));
      const bundleFingerprint = sha256(JSON.stringify(bundleFiles));
      let sourceCommit: string | null = null, sourceWorktreeDirty: boolean | null = null;
      try {
        sourceCommit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repoRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
        sourceWorktreeDirty = execFileSync('git', ['status', '--porcelain', '--', 'apps/explorer', 'packages/contracts'], { cwd: repoRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim().length > 0;
      } catch { /* An extracted runnable/source review does not require Git. */ }
      const identity = {
        schema_version: 1,
        build_id: 'chronicle-' + sha256(JSON.stringify({ source_fingerprint: sourceFingerprint, bundle_fingerprint: bundleFingerprint })),
        source_commit: sourceCommit,
        source_worktree_dirty: sourceWorktreeDirty,
        source_commit_meaning: 'Git HEAD at build time; source_fingerprint binds actual source bytes, including uncommitted changes. Later report-only commits may differ.',
        source_fingerprint: sourceFingerprint,
        source_file_count: sourceInputs.length,
        source_scope: ['apps/explorer/src/**', 'apps/explorer/research-semantic/** (excluding dependency/runtime caches)', 'apps/explorer/runtime-isolation/**', 'apps/explorer/verification-tools/** (excluding dependency/runtime caches)', 'packages/contracts/src/**', 'apps/explorer/public/**', 'apps/explorer/index.html', 'apps/explorer/production-review.html', 'apps/explorer/vite.config.ts', 'apps/explorer/package.json', 'apps/explorer/pnpm-lock.yaml'],
        bundle_fingerprint: bundleFingerprint,
        bundle_files: bundleFiles,
        deterministic_identity: 'No timestamps, absolute paths or Git metadata enter build_id; identical source and emitted bundle bytes produce the same identity.',
      };
      await writeFile(join(resolve(appRoot, options.dir ?? 'dist'), 'build-info.json'), JSON.stringify(identity, null, 2) + '\n');
    },
  };
}

export default defineConfig({
  plugins: [chronicleBuildIdentity()],
  base: './',
  server: {
    host: '0.0.0.0',
    port: 4173,
    strictPort: true,
    allowedHosts: ['terminal.local'],
    fs: { allow: [fileURLToPath(new URL('../..', import.meta.url))] },
  },
});
