#!/usr/bin/env python3
"""Read-only, pinned derivation of the Milestone 1 research pilot.

Uses the already authorized local Teaching Atlas preview; never compiles or
rewrites historical/publication files. Python standard library only. --check
compares exact generated bytes without writing anything.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

APP = Path(__file__).resolve().parent.parent
CANONICAL_SHA = "ebc9a6ef20b1edfa3c957995b17e57c4b061a6ad89727ff1a2e0ac0983b53be5"
WORKBOOK_SHA = "3a96030d87aec6c1c50f658d5321067d6345e1ab936c5d2854524f972caa75c0"
SOURCE_ID = "un-wup-2025"
WORKBOOK_NAME = "WUP2025-F21-DEGURBA-Cities_Pop.xlsx"
SOURCE_EDITION = "POP/DB/WUP/Rev.2025/F21"
# These are registered reference identities, not an inferred spatial join.
ENTITIES = (
    ("hist-mexicocity-faaf2abd", 5439, "Mexico City"),
    ("hist-guadalajara-86f202e4", 3099, "Guadalajara"),
    ("hist-monterrey-f375b062", 6218, "Monterrey"),
    ("hist-puebla-d4160425", 5915, "Puebla"),
)
YEARS = tuple(range(1975, 2026, 5))
NS = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
REL = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
DEFINITION = (
    "Population residing in DEGURBA urban centres at mid-year. Cities use population, "
    "density and contiguity criteria (at least 1,500 inhabitants/km² and 50,000 inhabitants). "
    "This is not a municipal administrative population; constant geographic footprints "
    "across years are not established by the retained metadata."
)


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def pinned_bytes(path: Path, expected: str) -> bytes:
    data = path.read_bytes()
    require(hashlib.sha256(data).hexdigest() == expected, f"EDITION_MISMATCH: {path.name}")
    return data


def workbook_rows(path: Path) -> tuple[dict[str, object], dict[int, tuple[int, dict[str, object]]]]:
    """Resolve the Data sheet and its precise cells without a spreadsheet engine."""
    with zipfile.ZipFile(path) as archive:
        workbook = ET.fromstring(archive.read("xl/workbook.xml"))
        sheet = next((s for s in workbook.findall("s:sheets/s:sheet", NS) if s.get("name") == "Data"), None)
        require(sheet is not None, "INSUFFICIENT_EVIDENCE: Data sheet missing")
        rid = sheet.get(f"{{{REL}}}id")
        rels = ET.fromstring(archive.read("xl/_rels/workbook.xml.rels"))
        target = next((r.get("Target") for r in rels if r.get("Id") == rid), None)
        require(target is not None and target.startswith("worksheets/"), "Invalid pinned sheet relationship")
        shared = ET.fromstring(archive.read("xl/sharedStrings.xml"))
        strings = ["".join(i.itertext()) for i in shared.findall("s:si", NS)]
        wanted = {code for _, code, _ in ENTITIES}
        found: dict[int, tuple[int, dict[str, object]]] = {}
        headers: dict[str, object] = {}
        with archive.open("xl/" + target) as stream:
            for _, element in ET.iterparse(stream, events=("end",)):
                if element.tag != f"{{{NS['s']}}}row":
                    continue
                row_number = int(element.get("r", "0"))
                values: dict[str, object] = {}
                for cell in element.findall("s:c", NS):
                    ref = cell.get("r", "")
                    column = re.sub(r"\d+$", "", ref)
                    v = cell.find("s:v", NS)
                    raw = None if v is None else v.text
                    if raw is None:
                        values[column] = None
                    elif cell.get("t") == "s":
                        values[column] = strings[int(raw)]
                    elif cell.get("t") in (None, "n"):
                        require(cell.find("s:f", NS) is None, "Formula cells are not accepted as source observations")
                        values[column] = float(raw)
                    else:
                        values[column] = raw
                if row_number == 1:
                    headers = values
                code = values.get("G")
                if code in wanted:
                    require(code not in found, f"Duplicate City_Code: {code}")
                    found[int(code)] = (row_number, values)
                element.clear()
        require(set(found) == wanted, "INSUFFICIENT_EVIDENCE: expected city rows missing")
        return headers, found


def derive(app: Path) -> dict[str, object]:
    canonical_path = app / "public/history/cities.json"
    workbook_path = app / "public/history/source" / WORKBOOK_NAME
    canonical = json.loads(pinned_bytes(canonical_path, CANONICAL_SHA))
    pinned_bytes(workbook_path, WORKBOOK_SHA)
    require(canonical.get("version") == 1 and canonical.get("yearNumbering") == "astronomical", "Unsupported city data semantics")
    manifest = json.loads((app / "public/history/city-build-manifest.json").read_text())
    require(manifest["output"]["sha256"] == CANONICAL_SHA, "Canonical manifest mismatch")
    require(any(i["file"] == WORKBOOK_NAME and i["sha256"] == WORKBOOK_SHA for i in manifest["inputs"]), "Workbook manifest mismatch")
    registry = next((s for s in canonical["sources"] if s["id"] == SOURCE_ID), None)
    require(registry is not None and registry.get("license") == "CC BY 3.0 IGO", "Missing source/rights metadata")
    headers, source_rows = workbook_rows(workbook_path)
    require(headers.get("G") == "City_Code" and headers.get("J") == "PWCent_Longitude" and headers.get("K") == "PWCent_Latitude", "Workbook structure mismatch")
    year_columns = {int(str(value).removesuffix(".0")): col for col, value in headers.items()
                    if str(value).removesuffix(".0").isdigit() and int(str(value).removesuffix(".0")) in YEARS}
    require(set(year_columns) == set(YEARS), "Missing required year columns")
    entities = []
    observations = []
    for entity_id, source_code, label in ENTITIES:
        matches = [(i, c) for i, c in enumerate(canonical["cities"]) if c["id"] == entity_id]
        require(len(matches) == 1, f"Ambiguous/missing canonical entity: {entity_id}")
        city_index, city = matches[0]
        require(city.get("unCityCode") == source_code and city.get("referenceCountry") == "Mexico", "Canonical identity mismatch")
        row_number, row = source_rows[source_code]
        require(row.get("B") == "Mexico", "Source country-reference mismatch")
        coordinates = city.get("modernReferenceCoordinates")
        require(isinstance(coordinates, list) and len(coordinates) == 2, "Missing UN reference coordinates")
        require(abs(coordinates[0] - row["J"]) < 1e-11 and abs(coordinates[1] - row["K"]) < 1e-11, "Coordinate lineage mismatch")
        entities.append({"id": entity_id, "label": label, "coordinates": coordinates,
                         "geographicDefinition": DEFINITION, "definitionStatus": "explicit", "spatialComparability": "definition-only"})
        for year in YEARS:
            matches = [(i, o) for i, o in enumerate(city["population"]) if o["sourceId"] == SOURCE_ID and o["year"] == year]
            require(len(matches) == 1, f"Missing/duplicate observation: {entity_id} {year}")
            observation_index, observation = matches[0]
            column = year_columns[year]
            raw = row.get(column)
            require(isinstance(raw, (int, float)) and math.isfinite(raw) and raw > 0, "Missing/nonpositive raw population")
            require(round(raw * 1000) == observation["value"], f"NUMERIC_MISMATCH: {entity_id} {year}")
            observations.append({"id": f"{entity_id}:{SOURCE_ID}:{year}", "entityId": entity_id,
                "year": year, "value": observation["value"], "sourceValue": raw, "unit": "persons",
                "precision": "year", "dateMeaning": "mid-year estimate", "evidenceType": "estimate",
                "reviewStatus": "source-attributed", "uncertainty": None,
                "locator": {"row": row_number, "column": column, "cell": f"{column}{row_number}",
                            "jsonPointer": f"/cities/{city_index}/population/{observation_index}"}})
    return {"schemaVersion": 1, "id": "un-wup-2025-mexico-four", "edition": "chronicle-teaching-local-2026-09-27/un-wup-2025-f21-v1",
        "definition": DEFINITION,
        "coverageNote": "Four selected Mexican urban centres, 1975–2025, at five-year checkpoints already retained by Chronicle. Not all cities or annual values. Original values are estimates in thousands, converted to rounded persons; no uncertainty interval is supplied. Footprints are not established as constant. No interpolation, pooled totals, or growth rates. Other historical-source series and future projections are excluded.",
        "source": {"id": SOURCE_ID, "title": "United Nations, Department of Economic and Social Affairs, Population Division (2025). World Urbanization Prospects: The 2025 Revision, Online Edition. File 21.",
            "url": registry["url"], "edition": SOURCE_EDITION, "sha256": WORKBOOK_SHA, "license": "CC BY 3.0 IGO",
            "rights": "authorized-local-preview", "file": WORKBOOK_NAME, "sheet": "Data", "sourceUnit": "thousands of persons", "conversion": "round(value * 1000)"},
        "canonical": {"path": "public/history/cities.json", "sha256": CANONICAL_SHA},
        "entities": entities, "observations": observations}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate exact existing output; do not write")
    args = parser.parse_args()
    try:
        data = (json.dumps(derive(APP), ensure_ascii=False, indent=2) + "\n").encode("utf-8")
        output = APP / "src/research/pilot-data.json"
        if args.check:
            require(output.read_bytes() == data, "Derived pilot differs: regenerate explicitly after reviewing source pins")
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_bytes(data)
        print(json.dumps({"status": "PASS", "mode": "check" if args.check else "derive", "observations": 44,
                          "entities": 4, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}))
        return 0
    except (ValueError, KeyError, OSError, zipfile.BadZipFile, ET.ParseError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
